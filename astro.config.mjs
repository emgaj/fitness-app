// @ts-check
import { defineConfig, envField } from "astro/config";

import react from "@astrojs/react";
import sitemap from "@astrojs/sitemap";
import tailwindcss from "@tailwindcss/vite";
import cloudflare from "@astrojs/cloudflare";

// https://astro.build/config
export default defineConfig({
  output: "server",
  integrations: [react(), sitemap()],
  vite: {
    plugins: [tailwindcss()],
  },
  // imageService is pinned explicitly: the adapter default flipped to "cloudflare-binding"
  // in Sept 2026 and regressed that same month. The app uses no astro:assets images, so
  // "passthrough" is the honest choice - no transformation, and no IMAGES binding
  // auto-provisioned on deploy. Revisit only when optimized images are actually needed.
  adapter: cloudflare({ imageService: "passthrough" }),
  env: {
    schema: {
      SUPABASE_URL: envField.string({ context: "server", access: "secret", optional: true }),
      SUPABASE_KEY: envField.string({ context: "server", access: "secret", optional: true }),
    },
  },
});
